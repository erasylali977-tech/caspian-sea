export function getLang() {
  const saved = localStorage.getItem("aq-lang");
  if (saved === "ru" || saved === "kk" || saved === "en") return saved;
  return "ru";
}

export function setLang(lang) {
  localStorage.setItem("aq-lang", lang);
}

export function bindLangSwitch() {
  const current = getLang();
  document.querySelectorAll("[data-set-lang]").forEach((btn) => {
    btn.classList.toggle("on", btn.getAttribute("data-set-lang") === current);
    btn.addEventListener("click", () => {
      setLang(btn.getAttribute("data-set-lang"));
      location.reload();
    });
  });
}

export function t(lang, key) {
  return dict[lang]?.[key] || dict.ru[key] || key;
}

export function applyLang(root, lang) {
  root.querySelectorAll("[data-i]").forEach((el) => {
    const key = el.getAttribute("data-i");
    const value = t(lang, key);
    if (el.hasAttribute("data-i-html")) el.innerHTML = value;
    else el.textContent = value;
  });
  document.documentElement.lang = lang;
}
